/// A row of decoded database values, keyed by column name.
///
/// `Entry` is the transport-neutral representation of a single database
/// row. The language layer compiles queries into `Entry` maps and the
/// driver layer decodes result rows into `Entry` maps.
pub type Entry = HashMap<String, Value>;

/// A consuming accessor for deserializing a single row into a typed entity.
///
/// Each call to [`get`](Self::get) removes the named field from the
/// underlying map, so fields must be consumed exactly once.
/// Deserializer cursor over an [`Entry`]. Fields are removed as they are read.
pub struct EntryParser(Entry);

impl EntryParser {
    /// Extract a single field, converting it to `T`.
    ///
    /// Returns [`Error::NoField`] if the field is absent and
    /// [`Error::TypeMismatch`] if the value cannot be converted.
    pub fn get<T: FieldType>(&mut self, field: &str) -> crate::Result<T> {
        self.0
            .remove(field)
            .ok_or(Error::NoField(field.to_owned()))
            .and_then(T::try_from_value)
    }
}

impl Into<EntryParser> for Entry {
    fn into(self) -> EntryParser {
        EntryParser(self)
    }
}

/// Deterministic identity for an entity schema.
///
/// The identity is derived with FNV-1a from the table name, optionally
/// combined with the schema group as `"group::name"`. Its display form is
/// 16 lowercase hexadecimal digits. The value is useful for schema registries
/// and generated database object names; it is not a collision-proof durable
/// identifier for a versioned migration protocol.
///
/// Derived entities hash their table name, combined with the group/schema
/// name when present. Display formats the value as 16 lowercase hex digits.
#[derive(Serialize, Deserialize, Hash, Clone, Copy, Debug, PartialEq, Eq)]
pub struct EntityId(u64);

impl EntityId {
    /// Create an `EntityId` from a logical table name.
    pub fn new<I: Into<String>>(name: I) -> Self {
        let name = name.into();

        let mut hasher = fnv::FnvHasher::default();
        name.hash(&mut hasher);
        Self(hasher.finish())
    }

    /// Create an `EntityId` from a schema group and a logical table name.
    ///
    /// The group is joined to the name as `"group::name"` before hashing,
    /// so two entities with the same name in different groups receive
    /// distinct identifiers.
    pub fn new_with_group<T1: Display, T2: Display>(group: T1, name: T2) -> Self {
        Self::new(format!("{}::{}", group, name))
    }
}

impl Display for EntityId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_fmt(format_args!("{:016x}", self.0))
    }
}

/// Reconstructs a typed entity from a decoded row and its joined children.
pub trait EntityLike: Sized {
    /// Build the requested value from a row and the response for its joins.
    fn from_data(entry: Entry, sub_entries: Vec<QueryResponse>) -> crate::Result<Self>;
}

/// The core trait implemented by `#[derive(Entity)]`.
///
/// Implementations are generated by the `Entity` derive macro. They expose
/// the entity's schema, primary keys, and the standard CRUD operations.
/// Model contract implemented by `#[derive(Entity)]`.
pub trait Entity: 'static {
    /// The fluent builder type generated for this entity.
    type Builder: Default;
    /// The typed condition builder generated for this entity.
    type ConditionBuilder: Default;
    /// The typed order-by builder generated for this entity.
    type OrderByBuilder: Default;

    /// The stable identity used to register the entity with an [`Ormify`] engine.
    fn entity_id() -> EntityId;
    /// The database schema (fields, constraints) for this entity.
    fn scheme() -> Scheme;
    /// The names of the fields that form the primary key.
    fn primary_key_fields() -> Vec<String>;
    /// Serialize this entity into a transport-neutral [`Entry`].
    fn to_entry(self) -> Entry;
    /// Clone this entity into a transport-neutral [`Entry`].
    fn clone_to_entry(&self) -> Entry;
    /// Deserialize this entity from a decoded [`Entry`].
    fn from_entry(entry: EntryParser) -> crate::Result<Self>
    where
        Self: Sized;
    /// Apply any auto-updating fields (for example `modified_at`).
    fn update_fields(&mut self);
    /// Map a Rust field name to its database column name.
    fn get_key_name(field: &str) -> &str;

    /// Return a default builder for this entity.
    fn builder() -> Self::Builder {
        Default::default()
    }

    /// Begin a `SELECT` query for this entity.
    fn select() -> SelectBuilder<Self>
    where
        Self: Sized,
    {
        SelectBuilder::new()
    }

    /// Build a `SELECT` query for a related entity, constraining it to the
    /// rows that reference `self` through the foreign keys produced by `f`.
    fn select_children<E>(&self, f: impl FnOnce(E::FKB) -> E::FK) -> crate::Result<SelectBuilder<E>>
    where
        Self: Sized,
        E: JoinBuilder<Self>,
    {
        let mut entry = self.clone_to_entry();
        let pairs = E::get_pairs(f(Default::default()));
        let condition = pairs
            .into_iter()
            .map(|(name, field)| {
                let value = entry.remove(&field).ok_or_else(|| Error::TypeMismatch)?;
                Ok((name, value))
            })
            .collect::<crate::Result<Condition>>()?;

        Ok(E::select().where_(|_| condition))
    }

    /// Build a `DELETE` execution for this entity.
    ///
    /// The closure receives the entity's typed condition builder.
    fn delete<F>(f: F) -> Execution
    where
        F: FnOnce(&Self::ConditionBuilder) -> Condition,
        Self: Sized,
    {
        let condition_builder = Self::ConditionBuilder::default();
        let condition = f(&condition_builder);
        Execution::Delete {
            entity_id: Self::entity_id(),
            condition,
        }
    }

    /// Build an `Init` execution that creates the entity's table.
    fn init() -> Execution
    where
        Self: Sized,
    {
        Execution::Init {
            entity_id: Self::entity_id(),
            scheme: Self::scheme(),
        }
    }

    /// Create an insert execution from this entity.
    fn insert(self) -> Execution
    where
        Self: Sized,
    {
        Execution::Insert {
            entity_id: Self::entity_id(),
            entry: self.to_entry(),
        }
    }
}

impl<T: Entity> EntityLike for T {
    fn from_data(entry: Entry, _: Vec<QueryResponse>) -> crate::Result<Self> {
        T::from_entry(entry.into())
    }
}

/// Parses the ordered child-query responses into a typed tuple of collections.
///
/// Each tuple member corresponds to one join declared at the current level.
pub trait Entities {
    /// Tuple of per-join child result collections.
    type VecSelf: Sized;
    /// Parse child responses in join declaration order.
    fn parse(sub_entries: Vec<QueryResponse>) -> crate::Result<Self::VecSelf>;
}

macro_rules! impl_entities {
    ($($letter:ident),*) => {
        #[allow(unused_parens)]
        impl<$($letter: EntityLike),*> Entities for ($($letter),*) {
            type VecSelf = ($(Vec<$letter>),*);
            fn parse(sub_entries: Vec<QueryResponse>) -> crate::Result<Self::VecSelf> {
                $(#[allow(non_snake_case)] let mut $letter = Vec::new();)*

                let mut iter = sub_entries.into_iter();

                $(
                    for (entry, sub_entries) in iter.next().ok_or(Error::TypeMismatch)? {
                        $letter.push($letter :: from_data(entry, sub_entries)?);
                    }
                )*

                Ok(($($letter),*))
            }
        }
    };
}

impl_entities!(A);
impl_entities!(A, B);
impl_entities!(A, B, C);
impl_entities!(A, B, C, D);
impl_entities!(A, B, C, D, E);
impl_entities!(A, B, C, D, E, F);
impl_entities!(A, B, C, D, E, F, G);
impl_entities!(A, B, C, D, E, F, G, H);
impl_entities!(A, B, C, D, E, F, G, H, I);
impl_entities!(A, B, C, D, E, F, G, H, I, J);

/// An entity paired with its original row snapshot for diff-based updates.
///
/// It dereferences to the wrapped entity. [`update`](Self::update) persists
/// changed fields; [`delete`](Self::delete) targets the original primary key.
pub struct Observer<T: Entity> {
    entity: T,
    original_entry: Entry,
}

impl<T: Entity + Debug> Debug for Observer<T> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        self.entity.fmt(f)
    }
}
impl<T: Entity + Display> Display for Observer<T> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        self.entity.fmt(f)
    }
}

impl<T: Entity> Entity for Observer<T> {
    type Builder = T::Builder;

    type ConditionBuilder = T::ConditionBuilder;

    type OrderByBuilder = T::OrderByBuilder;

    fn entity_id() -> EntityId {
        T::entity_id()
    }

    fn scheme() -> Scheme {
        T::scheme()
    }

    fn primary_key_fields() -> Vec<String> {
        T::primary_key_fields()
    }

    fn to_entry(self) -> Entry {
        self.entity.to_entry()
    }

    fn clone_to_entry(&self) -> Entry {
        self.entity.clone_to_entry()
    }

    fn from_entry(entry: EntryParser) -> crate::Result<Self>
    where
        Self: Sized,
    {
        T::from_entry(entry).map(Observer::new)
    }

    fn update_fields(&mut self) {
        self.entity.update_fields();
    }

    fn get_key_name(field: &str) -> &str {
        T::get_key_name(field)
    }

    fn select_children<E>(&self, f: impl FnOnce(E::FKB) -> E::FK) -> crate::Result<SelectBuilder<E>>
    where
        Self: Sized,
        E: JoinBuilder<Self>,
    {
        let pairs = E::get_pairs(f(Default::default()));
        let condition = pairs
            .into_iter()
            .map(|(name, field)| {
                let value = self
                    .original_entry
                    .get(&field)
                    .ok_or_else(|| Error::TypeMismatch)?
                    .clone();
                Ok((name, value))
            })
            .collect::<crate::Result<Condition>>()?;

        Ok(E::select().where_(|_| condition))
    }
}

impl<T, E> JoinBuilder<Observer<T>> for E
where
    T: Entity,
    E: JoinBuilder<T>,
{
    type FKB = E::FKB;

    type FK = E::FK;

    fn get_pairs(fk: Self::FK) -> Vec<(String, String)> {
        E::get_pairs(fk)
    }
}

impl<T: Entity> Deref for Observer<T> {
    type Target = T;

    fn deref(&self) -> &Self::Target {
        &self.entity
    }
}
impl<T: Entity> DerefMut for Observer<T> {
    fn deref_mut(&mut self) -> &mut <Self as Deref>::Target {
        &mut self.entity
    }
}

impl<T: Entity> Observer<T> {
    /// Capture the entity's current values as the original snapshot.
    pub fn new(entity: T) -> Self {
        let original_entry = entity.clone_to_entry();

        Self {
            entity,
            original_entry,
        }
    }

    fn make_condition(mut original_entry: Entry) -> Condition {
        T::primary_key_fields()
            .into_iter()
            .filter_map(|key| original_entry.remove(&key).map(|value| (key, value)))
            .collect()
    }

    /// Create an update execution containing fields changed since the snapshot.
    pub fn update(mut self) -> Execution {
        let entity_id = T::entity_id();

        self.update_fields();

        let Self {
            original_entry,
            entity,
        } = self;

        let mut entry = entity.to_entry();

        for key in original_entry.keys() {
            if entry.get(key) == original_entry.get(key) {
                entry.remove(key);
            }
        }

        let condition = Self::make_condition(original_entry);

        Execution::Update {
            entity_id,
            entry,
            condition,
        }
    }

    /// Create a delete execution targeting the snapshot's original primary key.
    pub fn delete(self) -> Execution {
        self.delete_and_unwrap().0
    }

    /// Create a delete execution and return the wrapped entity alongside it.
    pub fn delete_and_unwrap(self) -> (Execution, T) {
        let entity_id = T::entity_id();

        let Self {
            original_entry,
            entity,
        } = self;

        let condition = Self::make_condition(original_entry);

        (
            Execution::Delete {
                entity_id,
                condition,
            },
            entity,
        )
    }
}

/// One query result with typed collections for its joined children.
///
/// `T2` is a tuple of `Vec<Child>` values in join declaration order. For
/// recursive joins, a child may itself be `Joined<ChildEntity, (...)>`.
pub struct Joined<T1: Entity, T2: Entities> {
    pub entity: T1,
    pub children: T2::VecSelf,
}

impl<T1: Entity, T2: Entities> EntityLike for Joined<T1, T2> {
    fn from_data(entry: Entry, sub_entries: Vec<QueryResponse>) -> crate::Result<Self> {
        let entity = T1::from_entry(entry.into())?;

        let children = T2::parse(sub_entries)?;

        Ok(Self { entity, children })
    }
}
